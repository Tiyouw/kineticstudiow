"""Port the Mix A canvas CSS (scoped .m = 390 mobile design, .d = 1440 desktop design)
into one responsive stylesheet: .m rules -> max-width:1023px, .d rules -> min-width:1024px.
Usage: python3 scripts/port-css.py IN1.css [IN2.css ...] > src/styles/kinetic.css"""
import re, sys

def split_top(css):
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0: break
        sel = css[i:j].strip(); depth, k = 1, j + 1
        while depth and k < n:
            depth += {'{': 1, '}': -1}.get(css[k], 0); k += 1
        out.append((sel, css[j + 1:k - 1])); i = k
    return out

def scope(s):
    s = s.strip()
    if re.match(r'^#page\.d\b', s) or re.match(r'^\.d(?=[\s.#:\[>])', s): kind = 'd'
    elif re.match(r'^#page\.m\b', s) or re.match(r'^\.m(?=[\s.#:\[>])', s): kind = 'm'
    else: return 'g', s
    s = re.sub(r'^#page\.[md]\b', '#page', s)
    s = re.sub(r'^\.[md](?=[\s.#:\[>])\s*', '', s) or 'body'
    return kind, s

g, m, d = [], [], []
for f in sys.argv[1:]:
    css = re.sub(r'/\*.*?\*/', '', open(f).read(), flags=re.S)
    for sel, body in split_top(css):
        if sel.startswith('@'):
            g.append('%s{%s}' % (sel, body)); continue
        buckets = {'g': [], 'm': [], 'd': []}
        for s in sel.split(','):
            k, s2 = scope(s); buckets[k].append(s2)
        for k, tgt in (('g', g), ('m', m), ('d', d)):
            if buckets[k]: tgt.append('%s{%s}' % (','.join(buckets[k]), body.strip()))
print('/* Generated by scripts/port-css.py from the Mix A canvas. Edit freely; regenerate only on purpose. */')
print('\n'.join(g))
print('@media (max-width:1023px){\n' + '\n'.join(m) + '\n}')
print('@media (min-width:1024px){\n' + '\n'.join(d) + '\n}')
